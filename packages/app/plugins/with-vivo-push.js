const fs = require("node:fs");
const path = require("node:path");
const {
  withAndroidManifest,
  withAppBuildGradle,
  withDangerousMod,
} = require("expo/config-plugins");

// vivo push SDK integration. Enabled only when the SDK aar and the AppID/AppKey exist on this
// machine (never committed): see resolveVivoPushConfig. Otherwise the plugin is not applied at all
// and the Android project is identical to a build without vivo.

const AAR_NAME = "vivo_push.aar";
const KOTLIN_DIR = ["app", "src", "main", "java", "sh", "paseo", "vivo"];
const RECEIVER_CLASS = "sh.paseo.vivo.PaseoVivoPushReceiver";
const GRADLE_DEPENDENCY = `implementation(files("libs/${AAR_NAME}"))`;

function readJson(file, fsImpl) {
  try {
    return JSON.parse(fsImpl.readFileSync(file, "utf8"));
  } catch {
    return {};
  }
}

/**
 * Returns { aarPath, appId, appKey } or null when any of the three is missing.
 * Sources, in order: env VIVO_PUSH_SDK_AAR / VIVO_APP_ID / VIVO_APP_KEY, then
 * `.secrets/vivo/*.aar` and `.secrets/vivo/config.json` ({"appId","appKey"}) under the app
 * directory or the repository root (both are gitignored).
 */
function resolveVivoPushConfig({ env = process.env, appDir, repoRoot, fsImpl = fs } = {}) {
  const secretDirs = [appDir, repoRoot]
    .filter(Boolean)
    .map((dir) => path.join(dir, ".secrets", "vivo"));
  const fromFiles = secretDirs.map((dir) => readJson(path.join(dir, "config.json"), fsImpl));
  const pick = (envKey, field) =>
    (env[envKey] || "").trim() ||
    fromFiles
      .map((c) => c[field])
      .find(Boolean)
      ?.toString()
      .trim();

  let aarPath = (env.VIVO_PUSH_SDK_AAR || "").trim();
  if (!aarPath) {
    for (const dir of secretDirs) {
      try {
        const aar = fsImpl.readdirSync(dir).find((name) => name.endsWith(".aar"));
        if (aar) {
          aarPath = path.join(dir, aar);
          break;
        }
      } catch {
        // directory absent
      }
    }
  }
  const appId = pick("VIVO_APP_ID", "appId");
  const appKey = pick("VIVO_APP_KEY", "appKey");
  if (!aarPath || !appId || !appKey || !fsImpl.existsSync(aarPath)) return null;
  return { aarPath, appId, appKey };
}

function upsertMeta(application, name, value) {
  const list = (application["meta-data"] ??= []);
  const existing = list.find((m) => m.$["android:name"] === name);
  if (existing) existing.$["android:value"] = value;
  else list.push({ $: { "android:name": name, "android:value": value } });
}

/** Adds the vivo meta-data and the message receiver to the manifest object. Idempotent. */
function applyVivoManifest(manifest, { appId, appKey }) {
  const application = manifest.manifest.application?.[0];
  if (!application)
    throw new Error("Could not add vivo push without an application manifest entry");
  upsertMeta(application, "com.vivo.push.app_id", String(appId));
  upsertMeta(application, "com.vivo.push.api_key", String(appKey));
  const receivers = (application.receiver ??= []);
  if (!receivers.some((r) => r.$["android:name"] === RECEIVER_CLASS)) {
    receivers.push({
      $: { "android:name": RECEIVER_CLASS, "android:exported": "false" },
      "intent-filter": [
        { action: [{ $: { "android:name": "com.vivo.pushclient.action.RECEIVE" } }] },
      ],
    });
  }
  return manifest;
}

/** Adds the aar dependency to app/build.gradle contents. Idempotent. */
function applyVivoGradle(contents) {
  if (contents.includes(GRADLE_DEPENDENCY)) return contents;
  if (!/dependencies\s*\{/.test(contents)) {
    throw new Error("Could not add the vivo push SDK: no dependencies block in app/build.gradle");
  }
  return contents.replace(/dependencies\s*\{/, (m) => `${m}\n    ${GRADLE_DEPENDENCY}`);
}

const RECEIVER_KT = `package sh.paseo.vivo

import android.content.Context
import android.content.Intent
import com.vivo.push.model.UPSNotificationMessage
import com.vivo.push.sdk.OpenClientPushMessageReceiver
import org.json.JSONObject

/** Receives vivo push callbacks. Generated by with-vivo-push; do not edit. */
class PaseoVivoPushReceiver : OpenClientPushMessageReceiver() {
  override fun onReceiveRegId(context: Context, regId: String) {
    prefs(context).edit().putString("reg_id", regId).apply()
  }

  // skipType 3: the tap comes here with the message's custom data. Stash it for JS and open the app.
  override fun onNotificationMessageClicked(context: Context, msg: UPSNotificationMessage) {
    val data = JSONObject()
    msg.params?.forEach { (k, v) -> data.put(k, v) }
    prefs(context).edit().putString("pending_click", data.toString()).apply()
    context.packageManager.getLaunchIntentForPackage(context.packageName)?.let {
      it.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP)
      context.startActivity(it)
    }
  }

  private fun prefs(context: Context) =
    context.getSharedPreferences("paseo_vivo_push", Context.MODE_PRIVATE)
}
`;

const BRIDGE_KT = `package sh.paseo.vivo

import android.content.Context
import com.vivo.push.PushClient

/** The only SDK entry point used by the paseo-vivo-push module (via reflection). Generated by with-vivo-push. */
object VivoPushBridge {
  @JvmStatic
  fun isSupported(context: Context): Boolean = PushClient.getInstance(context).isSupport

  @JvmStatic
  fun turnOn(context: Context) {
    val client = PushClient.getInstance(context)
    client.initialize()
    client.turnOnPush { }
  }

  @JvmStatic
  fun regId(context: Context): String? = PushClient.getInstance(context).regId
}
`;

function withVivoPush(config, options) {
  const { aarPath, appId, appKey } = options;
  config = withAndroidManifest(config, (mod) => {
    applyVivoManifest(mod.modResults, { appId, appKey });
    return mod;
  });
  config = withAppBuildGradle(config, (mod) => {
    mod.modResults.contents = applyVivoGradle(mod.modResults.contents);
    return mod;
  });
  return withDangerousMod(config, [
    "android",
    (mod) => {
      const androidRoot = mod.modRequest.platformProjectRoot;
      const libs = path.join(androidRoot, "app", "libs");
      const kotlin = path.join(androidRoot, ...KOTLIN_DIR);
      fs.mkdirSync(libs, { recursive: true });
      fs.mkdirSync(kotlin, { recursive: true });
      fs.copyFileSync(aarPath, path.join(libs, AAR_NAME));
      fs.writeFileSync(path.join(kotlin, "PaseoVivoPushReceiver.kt"), RECEIVER_KT);
      fs.writeFileSync(path.join(kotlin, "VivoPushBridge.kt"), BRIDGE_KT);
      return mod;
    },
  ]);
}

module.exports = withVivoPush;
module.exports.resolveVivoPushConfig = resolveVivoPushConfig;
module.exports.applyVivoManifest = applyVivoManifest;
module.exports.applyVivoGradle = applyVivoGradle;
module.exports.RECEIVER_KT = RECEIVER_KT;
module.exports.BRIDGE_KT = BRIDGE_KT;
